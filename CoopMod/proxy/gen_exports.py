#!/usr/bin/env python3
"""Generate the export headers and bos_proxy.def from the ORIGINAL Bos.dll.

usage: gen_exports.py <original Bos.dll> <out_dir>

The engine resolves every Export* by name and aborts mod loading if one is
missing, so the proxy must export exactly the same names. Reading them from
the real export table (instead of typing them) keeps the two in sync.
"""
import os
import struct
import sys

# Called every frame (or several times per frame). Logged only on the first
# calls and then summarised periodically, otherwise the log would explode.
PER_FRAME = {
    "ExportUpdateRenderModAfterAll",
    "ExportUpdateRenderModBeforeAll",
    "ExportUpdateRenderModForStats",
    "ExportUpdateSimulationMod",
    "ExportUpdateSimulationModAfterEntitiesSimulation",
    "ExportUpdateSimulationModBeforeEntitiesSimulation",
    "ExportUpdateSimulationModSlave",
    "ExportGetModInputCommand",
    "ExportGetShiftableInput",
    "ExportDispatchEvent",
    "ExportDiscardPendingEvents",
    "ExportGetEventEncodingTable",
    "ExportGetLocalPlayerVehicle",
    "ExportGetPlayerVehicle",
    "ExportOnRebuildEventBoxes",
    "ExportGetNbrEntityTypes",
    "ExportGetPlayerEntityType",
    "ExportOnPlayerPingJustChange",
    "ExportDeleteEntities",  # once per entity on level unload: hundreds of lines
}


def read_exports(path):
    d = open(path, "rb").read()
    e = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, e + 6)[0]
    optsz = struct.unpack_from("<H", d, e + 20)[0]
    opt = e + 24
    exp_rva = struct.unpack_from("<I", d, opt + 96)[0]
    secs = []
    for i in range(nsec):
        o = opt + optsz + i * 40
        vs, va, rs, rp = struct.unpack_from("<IIII", d, o + 8)
        secs.append((va, max(vs, rs), rp))

    def off(rva):
        for va, sz, rp in secs:
            if va <= rva < va + sz:
                return rp + rva - va
        raise ValueError(hex(rva))

    def cstr(rva):
        o = off(rva)
        return d[o:d.index(b"\0", o)].decode("ascii")

    o = off(exp_rva)
    base, nfunc, nname, f_rva, n_rva, o_rva = struct.unpack_from("<IIIIII", d, o + 16)
    out = []
    for i in range(nname):
        name = cstr(struct.unpack_from("<I", d, off(n_rva) + i * 4)[0])
        ordinal = struct.unpack_from("<H", d, off(o_rva) + i * 2)[0] + base
        out.append((ordinal, name))
    out.sort()
    return out


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    exports = read_exports(src)
    if len(exports) != 64:
        print(f"warning: expected 64 exports, found {len(exports)}")

    h = []
    h.append("/* GENERATED by gen_exports.py from the original Bos.dll - do not edit. */")
    h.append(f"#define NUM_EXPORTS {len(exports)}")
    h.append("static const char *const g_export_names[NUM_EXPORTS] = {")
    h += [f'    "{n}",' for _, n in exports]
    h.append("};")
    h.append("/* 1 = called every frame: log first calls only, then periodic counts */")
    h.append("static const unsigned char g_export_per_frame[NUM_EXPORTS] = {")
    h += [f"    {1 if n in PER_FRAME else 0}, /* {n} */" for _, n in exports]
    h.append("};")
    open(os.path.join(outdir, "exports_gen_names.h"), "w", newline="\r\n").write("\n".join(h) + "\n")

    stubs = ["/* GENERATED by gen_exports.py from the original Bos.dll - do not edit. */"]
    stubs += [f"EXPORT_STUB({i}, {n})" for i, (_, n) in enumerate(exports)]
    open(os.path.join(outdir, "exports_gen_stubs.h"), "w", newline="\r\n").write("\n".join(stubs) + "\n")

    dfile = ["LIBRARY Bos", "EXPORTS"]
    for ordinal, n in exports:
        dfile.append(f"    {n} = Stub_{n} @{ordinal}")
    dfile.append("    CoopMod_Version")
    open(os.path.join(outdir, "bos_proxy.def"), "w", newline="\r\n").write("\n".join(dfile) + "\n")
    print(f"generated {len(exports)} export stubs into {outdir}")


if __name__ == "__main__":
    main()
